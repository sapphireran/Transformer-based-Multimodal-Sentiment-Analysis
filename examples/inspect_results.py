#!/usr/bin/env python3
"""Reprint the checked-in MOSI / MOSEI CSV tables, ranked by MAE.

Run from the repository root:

    python examples/inspect_results.py
"""

from __future__ import annotations

from pathlib import Path
import sys
import csv
from typing import List

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from examples._bootstrap import REPO_ROOT, ensure_output_dir

TABLES = [
    ("MOSEI BERT fusion", "model/results/main_results.csv"),
    ("MOSEI BERT GMTM ablation", "model/ablation_results.csv"),
    ("MOSEI GloVe fusion", "model/results/glove_results.csv"),
    ("MOSEI GloVe GMTM ablation", "model/ablation_glove_results.csv"),
    ("MOSI BERT transfer", "model/mosi_test/mosi_bert_results.csv"),
    ("MOSI BERT GMTM ablation", "model/mosi_test/ablation_mosi_results.csv"),
    ("MOSI GloVe transfer", "model/mosi_test/mosi_glove_results.csv"),
    ("MOSI GloVe GMTM ablation", "model/mosi_test/ablation_mosi_glove_results.csv"),
]


def _read(path: Path) -> List[dict]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _mae_key(row: dict) -> float:
    return float(row.get("MAE", "inf"))


def _format(rows: List[dict]) -> str:
    if not rows:
        return "_empty_"
    headers = list(rows[0].keys())
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for row in sorted(rows, key=_mae_key):
        lines.append("| " + " | ".join(row[h] for h in headers) + " |")
    return "\n".join(lines)


def main() -> None:
    chunks = ["# Ranked result tables", "", "Generated by `examples/inspect_results.py`.", ""]
    for title, rel in TABLES:
        path = REPO_ROOT / rel
        print("=" * 72)
        print(title)
        print(path.relative_to(REPO_ROOT))
        if not path.exists():
            print("  MISSING")
            chunks.append(f"## {title}\n\n_missing {rel}_\n")
            continue
        rows = _read(path)
        best = min(rows, key=_mae_key)
        method_col = next(iter(best.keys()))
        print(f"  rows={len(rows)}  best MAE={best['MAE']}  ({best[method_col]})")
        print()
        table = _format(rows)
        print(table)
        print()
        chunks.append(f"## {title}\n\n{table}\n")

    out = ensure_output_dir() / "ranked_results.md"
    out.write_text("\n".join(chunks) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
